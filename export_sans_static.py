"""
Precompute the SANS monitor's API responses so the page can run as a static
site with no Python behind it.

The three read endpoints become a single JS bundle:

    GET /api/data         -> SANS_STATIC.data
    GET /api/demo         -> SANS_STATIC.demo
    GET /api/export       -> SANS_STATIC.exportCsv
    GET /api/export-linked-> SANS_STATIC.exportLinked

Everything that writes (record, baseline, settings, delete, intervention)
has no static equivalent: those calls fail with a clear message in the page.

Regenerate after changing sans_data.json or sans.py:

    python3 export_sans_static.py
"""
from __future__ import annotations

import csv
import io
import json
from pathlib import Path

import sans
import sans_web

ROOT = Path(__file__).resolve().parent
DATA = ROOT / 'sans_data.json'
OUT = ROOT / 'web' / 'sans-static.js'

SETTINGS = {'rate_review_threshold': None, 'prediction_days': None}


def export_csv(data):
    rows = [dict(eye=eye, **r)
            for eye in sans.EYES
            for r in sans.analyze(data, eye, **SETTINGS)]
    stream = io.StringIO()
    if rows:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    return stream.getvalue()


def build():
    real = sans.load_data(DATA)
    demo = sans.demo_data()
    demo['interventions'] = sans_web.interventions.demo_records()

    bundle = {
        'data': sans_web.payload(real, SETTINGS),
        'demo': sans_web.payload(demo, SETTINGS),
        'exportCsv': export_csv(real),
        'exportLinked': {
            'raw_records': real,
            'analysis': sans_web.payload(real, SETTINGS),
            'pairing': ('Latest scan strictly before start day; first scan strictly '
                        'after end day. Same-day scans excluded.'),
        },
        'readOnly': True,
    }
    text = ('// Generated by export_sans_static.py - do not edit.\n'
            'window.SANS_STATIC = '
            + json.dumps(bundle, ensure_ascii=False, separators=(',', ':'))
            + ';\n')
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding='utf-8')
    print(f'wrote {OUT}  ({OUT.stat().st_size / 1024:.1f} KB)')
    print(f"  data eyes: {list(bundle['data']['eyes'])}  "
          f"records: {sum(len(v['results']) for v in bundle['data']['eyes'].values())}")
    print(f"  demo records: {sum(len(v['results']) for v in bundle['demo']['eyes'].values())}")
    print(f"  csv rows: {len(bundle['exportCsv'].splitlines()) - 1}")


if __name__ == '__main__':
    build()
